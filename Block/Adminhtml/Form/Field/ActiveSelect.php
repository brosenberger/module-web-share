namespace BroCode\WebShare\Block\Adminhtml\Form\Field;

use Magento\Framework\View\Element\Html\Select;

/**
 * Yes/No select for the "Active" column of the share link rows.
 */
class ActiveSelect extends Select
{
    public function setInputName(string $value): self
    {
        return $this->setName($value);
    }

    public function setInputId(string $value): self
    {
        return $this->setId($value);
    }

    protected function _toHtml(): string
    {
        if (!$this->getOptions()) {
            $this->setOptions([['value' => '1', 'label' => __('Yes')], ['value' => '0', 'label' => __('No')]]);
        }

        return parent::_toHtml();
    }
}
